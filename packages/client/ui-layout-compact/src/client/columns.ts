/**
 * Pure concession-chain column solver for the compact three-column AppFrame.
 * Same contract as ui-layout's columns.ts, but with geometry constants tuned
 * for low-resolution screens (≤1366px wide).
 *
 * Chain order is fixed by contract: keep center >= CENTER_MIN by shrinking
 * details, then auto-closing it (derived zero width — preferred width
 * preferences are never rewritten, so widening the window restores them).
 * The sidebar never concedes: its rendered width is always the drag
 * preference (or the collapsed rail), and center absorbs any remaining
 * deficit as the last resort. Inputs are the layout store's plain width
 * preferences (0 = closed); a closed sidebar resolves to the fixed
 * SIDEBAR_COLLAPSED control rail while closed details resolve to zero width.
 * The SIDEBAR_AUTO_COLLAPSE breakpoint is consumed by AppFrame, which decides
 * the effective sidebar preference before solving; the solver itself stays
 * breakpoint-free.
 */

/** Resolved widths for one frame; center may drop below CENTER_MIN only at the final fallback. */
export interface Columns { sidebar: number; center: number; details: number }

// Contract-frozen geometry: the three-column concession chain's fixed points.
// All values are reduced from ui-layout's defaults for compact screens.

/** Center column floor; only the final fallback may go below it. */
export const CENTER_MIN = 480

/** Sidebar drag clamp floor. */
export const SIDEBAR_MIN = 180

/** Sidebar drag clamp ceiling. */
export const SIDEBAR_MAX = 320

/** Sidebar width before any user drag. */
export const SIDEBAR_DEFAULT = 220

/** Closed-sidebar rail: a 24px icon column with reduced horizontal paddings. */
export const SIDEBAR_COLLAPSED = 32

/** Viewport width below which the sidebar auto-collapses to the rail; tuned for
 * 1024px screens and smaller laptops. A manual toggle below it re-expands over
 * the squeezed center (stores.ts narrowExpanded). */
export const SIDEBAR_AUTO_COLLAPSE = 768

/** Details drag clamp floor. */
export const DETAILS_MIN = 260

/** Details drag clamp ceiling. */
export const DETAILS_MAX = 440

/** Details width before any user drag. */
export const DETAILS_DEFAULT = 300

/**
 * Clamp a panel width into its contract range.
 * @param px - requested width.
 * @param min - range lower bound.
 * @param max - range upper bound.
 * @returns the clamped width.
 */
export function clampWidth(px: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, Math.round(px)))
}

/**
 * Solve the three column widths for one viewport frame. Pure: no hysteresis —
 * the output is a function of (viewport, preferences) only, so recovery on
 * re-widening is automatic. Preferences re-clamp here because they cross the
 * store boundary and callers may still supply stale ranges.
 * @param viewport - available frame width in px.
 * @param sidebar - sidebar width preference in px (0 = closed).
 * @param details - details width preference in px (0 = closed).
 * @returns resolved widths; details 0 means visually closed (never unmounted), while a closed sidebar keeps its compact rail.
 */
export function computeColumns(viewport: number, sidebar: number, details: number): Columns {
  // The sidebar is fixed at its preference (or the rail) — it never concedes.
  const s = sidebar === 0 ? SIDEBAR_COLLAPSED : clampWidth(sidebar, SIDEBAR_MIN, SIDEBAR_MAX)
  const d0 = details === 0 ? 0 : clampWidth(details, DETAILS_MIN, DETAILS_MAX)

  // Step 1: everything fits at preferred widths.
  if (s + d0 + CENTER_MIN <= viewport) return { sidebar: s, center: viewport - s - d0, details: d0 }

  // Step 2: shrink details toward its minimum.
  const d1 = d0 === 0 ? 0 : Math.max(DETAILS_MIN, viewport - s - CENTER_MIN)
  if (s + d1 + CENTER_MIN <= viewport) return { sidebar: s, center: CENTER_MIN, details: d1 }

  // Step 3: auto-close details (derived — preferences untouched); center
  // absorbs any remaining deficit (may drop below CENTER_MIN).
  return { sidebar: s, center: Math.max(0, viewport - s), details: 0 }
}
